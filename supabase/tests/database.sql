-- Run ONLY against an empty disposable local Supabase database after migrations.
-- Example: psql "$LOCAL_DATABASE_URL" -v ON_ERROR_STOP=1 -f supabase/tests/database.sql
-- All test data rolls back. This script does not test concurrent connections.
begin;
do $test$
declare
  payload jsonb := '{"kind":"contact","organization":"","name":"Local Test","role":"","email":"local@example.org","phone":"","organizationType":"","town":"","staff":"","itSupport":"","services":[],"message":"Database test","reachBy":"Email","consent":false,"region":""}'::jsonb;
  result jsonb;
  test_hash text := repeat('a', 64);
  audit_row private.inbound_requests%rowtype;
  before_hits integer;
  i integer;
begin
  if has_schema_privilege('anon', 'private', 'USAGE') or has_schema_privilege('authenticated', 'private', 'USAGE') then
    raise exception 'Browser roles have private schema access';
  end if;
  if has_table_privilege('anon', 'private.inbound_requests', 'SELECT,INSERT,UPDATE,DELETE') or
     has_table_privilege('authenticated', 'private.inbound_requests', 'SELECT,INSERT,UPDATE,DELETE') or
     has_table_privilege('anon', 'private.inbound_rate_buckets', 'SELECT,INSERT,UPDATE,DELETE') or
     has_table_privilege('authenticated', 'private.inbound_rate_buckets', 'SELECT,INSERT,UPDATE,DELETE') then
    raise exception 'Browser roles have table privileges';
  end if;
  if has_function_privilege('anon', 'public.submit_inbound_request(jsonb,text)', 'EXECUTE') or
     has_function_privilege('authenticated', 'public.submit_inbound_request(jsonb,text)', 'EXECUTE') or
     not has_function_privilege('service_role', 'public.submit_inbound_request(jsonb,text)', 'EXECUTE') then
    raise exception 'Incorrect RPC privileges';
  end if;
  if exists (select 1 from pg_class c join pg_namespace n on n.oid = c.relnamespace
      where n.nspname = 'private' and c.relname in ('inbound_requests', 'inbound_rate_buckets')
      and (not c.relrowsecurity or not c.relforcerowsecurity)) then
    raise exception 'Missing forced RLS';
  end if;

  -- Unknown audit fields in the RPC payload cannot override database-generated values.
  result := public.submit_inbound_request(payload || '{"source":"spoof","inserted_at":"2000-01-01","inserted_by":"spoof","id":"00000000-0000-0000-0000-000000000000"}', test_hash);
  if result ->> 'saved' <> 'true' then raise exception 'Contact was not saved'; end if;
  select * into strict audit_row from private.inbound_requests where id = (result ->> 'request_id')::uuid;
  if audit_row.source <> 'Inbound form' or audit_row.inserted_by <> 'system' or audit_row.inserted_at < transaction_timestamp() or
     audit_row.id = '00000000-0000-0000-0000-000000000000'::uuid then
    raise exception 'Audit values were not generated by the database';
  end if;

  select sum(hits) into before_hits from private.inbound_rate_buckets where ip_hash = test_hash;
  begin
    perform public.submit_inbound_request(payload || '{"email":"invalid"}', test_hash);
    raise exception 'Invalid email was accepted';
  exception when check_violation then null;
  end;
  if (select sum(hits) from private.inbound_rate_buckets where ip_hash = test_hash) <> before_hits then
    raise exception 'Insert failure did not roll back rate counters';
  end if;
  for i in 2..5 loop
    result := public.submit_inbound_request(payload, test_hash);
    if result ->> 'saved' <> 'true' then raise exception 'Allowed request rejected'; end if;
  end loop;
  result := public.submit_inbound_request(payload, test_hash);
  if result ->> 'saved' <> 'false' or (result ->> 'retry_after')::integer not between 1 and 900 then
    raise exception 'Short window quota failed';
  end if;
  if (select count(*) from private.inbound_requests where email = 'local@example.org') <> 5 then
    raise exception 'Rate-limited request inserted a row';
  end if;

  -- Force expiration to prove stale buckets cannot block a fresh window.
  update private.inbound_rate_buckets set bucket_start = bucket_start - interval '2 days', expires_at = expires_at - interval '2 days' where ip_hash = test_hash;
  result := public.submit_inbound_request(payload, test_hash);
  if result ->> 'saved' <> 'true' or exists (select 1 from private.inbound_rate_buckets where ip_hash = test_hash and expires_at < clock_timestamp()) then
    raise exception 'Expiry cleanup or fresh quota failed';
  end if;
  update private.inbound_rate_buckets set hits = 20 where ip_hash = test_hash and window_seconds = 86400;
  result := public.submit_inbound_request(payload, test_hash);
  if result ->> 'saved' <> 'false' or (result ->> 'retry_after')::integer not between 1 and 86400 then
    raise exception 'Daily quota failed';
  end if;
  raise notice 'Database assertions passed; test transaction will roll back.';
end;
$test$;
rollback;
